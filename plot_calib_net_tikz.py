"""The paper's pose figures as pgfplots source, typeset with the paper itself: vector, in its own fonts.

Reads the CSVs of `plot_calib_net.py` and writes one .tex per graph for \\input in a figure environment; the
document needs \\usepackage{pgfplots}. Color = the network or solver, line style = the pose pipeline.

    python plot_calib_net_tikz.py figs/calib_net/calib_net_cathedral_ray.csv pose_different.tex
    python plot_calib_net_tikz.py figs/calib_net/calib_net_cathedral_eq_ray.csv pose_equal.tex
"""
import argparse
import collections
import csv

COLORS = {'cOursL': '1f77b4', 'cOursC': 'ff7f0e', 'cAny': 'e377c2', 'cGeo': '7f7f7f', 'cUni': 'bcbd22',
          'cSix': '2ca02c', 'cSeven': 'd62728', 'cNine': '9467bd', 'cTen': '8c564b'}
# drawn in this order, the last on top
NETWORKS = [('unik3d', 'cUni', r'UniK3D~\cite{piccinelli2025unik3d}', 'triangle*'), ('geocalib', 'cGeo', r'GeoCalib~\cite{veicht2024geocalib}', 'pentagon*'),
            ('anycalib_dist', 'cAny', r'AnyCalib$_\text{dist}$~\cite{tirado2025anycalib}', 'diamond*'),
            ('ours_ray_cnxt', 'cOursC', 'Ours ConvNeXt-T', 'square*'), ('ours_ray_vitl', 'cOursL', 'Ours ViT-L', '*')]
LEGEND_NETWORKS = ['ours_ray_vitl', 'ours_ray_cnxt', 'anycalib_dist', 'geocalib', 'unik3d']
BASELINES = {'k2Fk1_10pt': ('cTen', '*', r'10pt~\cite{kukelova2015efficient}'),
             'kFk_9pt': ('cNine', '*', r'9pt~\cite{fitzgibbon2001division,kocur2026minimal}'),
             'F_7pt_s3': ('cSeven', 'star', r'7pt, 3 $\lambda$~\cite{kocur2026minimal}'),
             'Efeq_6pt_s3': ('cSix', 'star', r'6pt, 3 $\lambda$~\cite{kocur2026minimal}')}
SOLVER_ORDER = ['F_7pt_s3', 'Efeq_6pt_s3', 'kFk_9pt', 'k2Fk1_10pt']
STYLES = {'E_5pt_V': 'solid', 'E_5pt_VLO': 'densely dotted', 'E_5pt_VLOeq': 'densely dotted',
          'Efeq_6pt_V': 'dashed', 'Efeq_6pt_VLO': 'densely dashdotted'}
PIPELINES = [('solid', r'5pt~\cite{nister2004efficient}'), ('densely dotted', '5pt + LO'), ('dashed', '6pt'), ('densely dashdotted', '6pt + LO')]
WIDTH = {'solid': 0.8, 'dashed': 0.7, 'densely dotted': 0.9, 'densely dashdotted': 0.7}


def read(path):
    d = collections.defaultdict(list)
    for r in csv.DictReader(open(path)):
        d[r['experiment']].append((float(r['runtime_ms']), float(r['mAA10'])))
    return {k: sorted(v) for k, v in d.items()}


def coords(points):
    return ' '.join(f'({x:.1f},{y:.2f})' for x, y in points)


def main():
    p = argparse.ArgumentParser()
    p.add_argument('csv')
    p.add_argument('out')
    a = a_args = p.parse_args()
    data = read(a.csv)
    eq = any('Efeq_6pt+' in k for k in data)

    baselines = [k for k in BASELINES if k in data]
    pipes = PIPELINES if eq else PIPELINES[:2]

    ys = [y for v in data.values() for _, y in v]
    xs = [x for v in data.values() for x, _ in v]
    ymin, ymax = 5 * int(min(ys) // 5), 5 * (int(max(ys) // 5) + 1)
    yticks = ','.join(str(v) for v in range(ymin, ymax + 1, 5 if ymax - ymin <= 35 else 10))
    out = ['% generated by rdnet/plot_calib_net_tikz.py from ' + a.csv.replace('\\', '/').split('/')[-1], r'\begin{tikzpicture}']
    out += [rf'\definecolor{{{k}}}{{HTML}}{{{v.upper()}}}' for k, v in COLORS.items()]
    out += [r'\begin{axis}[', r'  scale only axis, width=0.87\linewidth, height=0.52\linewidth,', r'  xmode=log, log basis x=10,',
            rf'  xmin={min(xs) * 0.92:.1f}, xmax={max(xs) * 1.08:.1f}, ymin={ymin}, ymax={ymax},',
            r'  xtick={30,50,100,200,300,500}, xticklabels={30,50,100,200,300,500}, minor xtick={},',
            rf'  ytick={{{yticks}}}, yticklabels={{{yticks}}},',
            r'  xlabel={Mean runtime per pair (ms)}, ylabel={Pose mAA at $10^\circ$ (\%)},',
            r'  label style={font=\footnotesize}, tick label style={font=\scriptsize},',
            r'  xlabel style={yshift=2pt}, ylabel style={yshift=-3pt},',
            r'  axis lines=left, axis line style={-, line width=0.4pt}, tick style={black, line width=0.4pt}, tick align=outside,',
            r'  major tick length=2pt, grid=major, grid style={black!12, line width=0.3pt},',
            r'  clip mode=individual, name=ax,',
            r']']
    for k in baselines:
        c, m, _ = BASELINES[k]
        out.append(rf'\addplot[{c}, line width=0.8pt, mark={m}, mark size=1.2pt] coordinates {{{coords(data[k])}}};')
    for method, c, _, m in NETWORKS:
        for k, v in sorted(data.items()):
            if '+' in k and k.split('+')[1].rsplit('_', 1)[0] == method:
                solver, net = k.split('+')
                s = STYLES[f'{solver}_{net.rsplit("_", 1)[1]}']
                out.append(rf'\addplot[{c}, {s}, line width={WIDTH[s]}pt, mark={m}, mark size=0.9pt, mark options={{solid}}] '
                           rf'coordinates {{{coords(v)}}};')
    out.append(r'\end{axis}')

    # the legend, above the plot: the networks in one row, the pipelines and solvers below them
    def sample(style):
        return rf'\tikz[baseline=-0.6ex]\draw[{style}, mark indices={{2}}] plot coordinates {{(0,0) (0.2,0) (0.4,0)}};'

    def row(items):
        return r'\hspace{6pt}'.join(r'\mbox{' + i + '}' for i in items)

    nets = {n: (c, label, m) for n, c, label, m in NETWORKS}
    networks = [sample(f'{nets[n][0]}, line width=0.8pt, mark={nets[n][2]}, mark size=1.1pt') + r'\,' + nets[n][1] for n in LEGEND_NETWORKS]
    lines = [sample(f'black!75, {st}, line width={WIDTH[st]}pt') + r'\,' + label for st, label in pipes]
    solvers = [sample(f'{BASELINES[k][0]}, line width=0.8pt, mark={BASELINES[k][1]}, mark size=1.2pt') + r'\,' + BASELINES[k][2]
               for k in SOLVER_ORDER if k in baselines]
    rows = [row(networks), row(lines), row(solvers)] if eq else [row(networks), row(lines + solvers)]
    out += [r'\node[anchor=south, inner sep=0pt, yshift=3pt] at (ax.outer north) {\resizebox{\linewidth}{!}{\scriptsize\begin{tabular}{@{}c@{}}']
    out += [' ' + r + r' \\' for r in rows[:-1]] + [' ' + rows[-1]]
    out += [r'\end{tabular}}};']
    out += [r'\end{tikzpicture}', '']
    open(a_args.out, 'w', newline='\n').write('\n'.join(out))
    print('wrote', a_args.out, len(data), 'curves')


if __name__ == '__main__':
    main()
